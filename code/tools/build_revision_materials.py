"""Build paper supplement tables and method schematic from saved evidence.
No raw-data experiment or method result is generated by this script.
"""
from pathlib import Path
import hashlib, json, math
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch
ROOT=Path(__file__).resolve().parents[1]
P=ROOT/'results/legacy_publication/pacificvis2027'; R=ROOT/'results'
NAMES=['era5','wildfire','olr','pm25','ring','gaussians']
LABELS=['ERA5','Fire','OLR','PM2.5','Ring','Gaussians']
sources={}
def read(name):
 p=R/(name+'.json'); sources[str(p.relative_to(ROOT))]=hashlib.sha256(p.read_bytes()).hexdigest();return json.loads(p.read_text())
def table(headers, rows, caption, label, widths=None):
 col=widths or ('l'+'r'*(len(headers)-1))
 return '\\begin{table}[H]\n\\centering\\small\n\\caption{'+caption+'}\\label{'+label+'}\n\\begin{tabular}{'+col+'}\\toprule\n'+' & '.join(headers)+r'\\\midrule'+'\n'+'\n'.join(' & '.join(map(str,row))+r'\\' for row in rows)+'\n\\bottomrule\\end{tabular}\n\\end{table}\n'
def pct(x):return f'{100*x:.1f}'
parts=[]
rows=[]
for n,l in zip(NAMES,LABELS):
 d=read('replicate_'+n)['certificate']; a=read('attainable_'+n)
 rows.append([l,d['frames'],f"{d['leaves'][0]}--{d['leaves'][1]}",d['tracks'],a['certificate']['conflict_frames_exact'],pct(a['certificate']['conflict_share_exact'])])
parts.append(table(['Data','Frames','Leaves/frame','Tracks','Conflicts','Conflict \\%'],rows,'Main-suite membership and exact conflicts ($H>0.02L$). Tracks are computed correspondences, not independently validated physical entities.','tab:suite'))
rows=[]
for n,l in zip(NAMES,LABELS):
 d=read('attainable_'+n); t=d['tightness'];o=next(x for x in d['ours'] if x['cap']==.2)
 rows.append([l,d['max_leaves'],f"{t['tight_within_half_pixel']}/{t['breakpoints']}",pct(t['gap_max']),f"{o['frames_pareto_optimal']}/{o['frames']}",pct(o['excess_over_attainable_mean_share']),pct(o['excess_over_attainable_max_share'])])
parts.append(table(['Data','$n_{\\max}$','Tight breaks','Max gap','R20 on $F$','Mean excess','Max excess'],rows,'Exact frontier diagnostics. Tightness is within half a pixel; gap is $F-\\Phi$ as a percentage of reference extent. R20 counts and excess concern fixed-order positional optima, excluding QP slack.','tab:frontier_checks'))
audit=read('method_performance_audit')
rows=[]; cirows=[]
for d in audit['results']:
 if d['dataset'] not in NAMES:continue
 l=LABELS[NAMES.index(d['dataset'])]; count=d['clear']; errs=d['total_errors']
 vals=[]
 for m in ['ST-MTM','A','R 20%']:
  v=errs.get(m); vals.append('--' if not count or v is None else f'{round(v*count)}/{count} ({100*v:.1f})')
 rows.append([l,*vals])
 for c in d.get('bootstrap_comparisons',[]):
  if c['method']=='R 20%' and c['other'] in ['ST-MTM','A']:
   q=c['err']; ci=q.get('ci95')
   if q.get('diff') is not None and ci is not None:
    cirows.append([l,c['other'],pct(q['diff']),f'[{pct(ci[0])}, {pct(ci[1])}]'])
parts.append(table(['Data','ST-MTM','Tree kept (A)','Relaxed (R20)'],rows,'Motion-proxy errors: error count / clear-event count (\\%). Events use $k=2$ and a 2\\% change threshold. A zero-event result is undefined.','tab:motion_counts'))
parts.append(table(['Data','Comparator','R20 minus comparator','95\\% interval'],cirows,'Paired circular moving-block bootstrap of total motion error, in percentage points. Block length is four steps. These are exploratory comparisons without multiplicity correction.','tab:bootstrap'))
# Robustness table shows the entire fixed-direction range and the automatic direction.
rob=read('robustness');rows=[]
for n,l in zip(NAMES[:4],LABELS[:4]):
 ds=rob[n];auto=ds[0];fixed=ds[1:]
 for th in [1,2,5]:
  key='share_theta_'+str(th)
  rows.append([l,th,pct(auto[key]),f'{pct(min(x[key] for x in fixed))}--{pct(max(x[key] for x in fixed))}'])
parts.append(table(['Data','$\\theta/L$ (\\%)','Automatic axis','Eight fixed axes'],rows,'Conflict-frame percentages by threshold and reference direction. The fixed-axis range reports all eight tested directions, rather than selecting the most favorable direction.','tab:directions'))
# Degree benchmark.
rows=[]
for d in read('benchmark_degree')['rows']:
 rows.append([d['root_degree'],d['subset_states'],f"{d['seconds']:.4f}",f"{d['tau']:.3f}"])
parts.append(table(['Root degree','Subset states','Seconds','Certificate (pixels)'],rows,'Degree stress test with 12 leaves and 96 pixels. The test changes hierarchy constraints as well as degree; timings describe this workload, not a general runtime guarantee.','tab:degree'))
# Finer extraction on the retained ERA5 period only.
d=read('independent_scale')['1999']
parts.append(r'\paragraph{Finer-scale ERA5 diagnosis.} At 150\,km, '+f"{d['certified_hierarchy_conflict_frames']}/{d['frames']} frames ({pct(d['certified_hierarchy_conflict_share'])}\\%) have a certified hierarchy-cost lower bound above 2\\% of the axis; the largest lower bound is {pct(d['hierarchy_cost_lower_max_share'])}\\%. The maximum leaf count is {d['leaves_max']}, with {d['frames_above_free_enumeration_limit']} frame above the free-enumeration limit. These are lower bounds from the relaxed pixel DP minus its rounding allowance and an upper bound for free placement. Full relaxation and motion results were not computed at this scale.\n")
# Selected protocol variants; preserve semantics and counts.
sens=read('sensitivity');rows=[]
for key in ['wildfire_cap8','wildfire_cap10','era5_s350','era5_crop']:
 d=sens[key]; proxy=d.get('proxy',{}); st=proxy.get('ST-MTM',{});rel=proxy.get('R 20%',{})
 rows.append([key.replace('_',r'\_'),d['frames'],d['leaves_max'],pct(d['conflict_share']),st.get('clear','--'),pct(st['error']) if 'error' in st else '--',pct(rel['error']) if 'error' in rel else '--'])
parts.append(table(['Protocol','Frames','$n_{\\max}$','Conflict \\%','Cases','ST error','R20 error'],rows,'Exploratory extraction controls for active real sequences. Error rates are percentages. Event sets change with extraction, so rows are not paired samples from a common event population.','tab:extraction'))
# Persistence is a separate experiment that deletes features.
rows=[]
for d in read('persistence')['era5']:
 rows.append([pct(d['eps']),pct(d['removed_share']),f"{d['mean_leaves']:.2f}",pct(d['conflict_share'])])
parts.append(table(['Persistence cutoff \\%','Removed leaves \\%','Mean leaves','Conflict \\%'],rows,'ERA5 persistence simplification. The cutoff is normalized by processed scalar range. This experiment removes extrema, whereas RG-MTM relaxation retains them.','tab:persistence'))
(P/'supplement_results.tex').write_text('\n'.join(parts))
# New code-native schematic; no experimental meaning encoded in unmeasured quantities.
plt.rcParams.update({'font.family':'DejaVu Sans','pdf.fonttype':42})
fig,ax=plt.subplots(figsize=(7.1,1.42));ax.set(xlim=(0,7.1),ylim=(0,1.42));ax.axis('off')
boxes=[(0.03,.40,1.14,.75,'1  INPUT','Fields, trees,\nextrema, tracks'),(1.48,.40,1.25,.75,'2  DIAGNOSE','Reference q\nPacking + hierarchy'),(3.04,.40,1.35,.75,'3  CONSTRUCT','Keep tree or relax\nBudgeted layout'),(4.70,.40,1.23,.75,'4  FILL','True leaf values\nOptimal barriers')]
for x,y,w,h,title,body in boxes:
 ax.add_patch(FancyBboxPatch((x,y),w,h,boxstyle='round,pad=0.02,rounding_size=0.035',facecolor='#f3f6f9',edgecolor='#44647a',lw=.8))
 ax.text(x+w/2,y+h-.14,title,ha='center',va='center',fontsize=8,weight='bold',color='#24475d')
 ax.text(x+w/2,y+.30,body,ha='center',va='center',fontsize=8,linespacing=1.5)
for x1,x2 in [(1.20,1.45),(2.77,3.01),(4.43,4.67),(5.97,6.14)]:
 ax.annotate('',xy=(x2,.78),xytext=(x1,.78),arrowprops=dict(arrowstyle='->',color='#44647a',lw=1.1))
ax.text(6.17,.97,'5  DISCLOSE',fontsize=8,weight='bold',color='#24475d')
ax.text(6.17,.66,'Map + error\nstrips',fontsize=8,linespacing=1.5)
ax.text(3.55,.16,'Lower certificate  |  Achieved position error  |  Measured merge-level error',ha='center',fontsize=8,color='#24475d')
fig.savefig(P/'figures/fig_method_overview.pdf',bbox_inches='tight',pad_inches=.03)
fig.savefig(P/'figures/fig_method_overview.png',dpi=240,bbox_inches='tight',pad_inches=.03);plt.close(fig)
(R/'revision_materials_manifest.json').write_text(json.dumps({'scope':'saved-evidence supplementary summaries; no new raw-data runs','source_sha256':sources,'generated':['supplement_results.tex','fig_method_overview.pdf']},indent=2)+'\n')
print('Generated supplement tables and method schematic from',len(sources),'evidence files')
